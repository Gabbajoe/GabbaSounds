#!/usr/bin/env python3
"""Import the two herb alert recordings without altering their original WAVs."""
import hashlib
import json
from pathlib import Path

import build_noggenfogger
from preview_herbalism import encode, HERBS, write_preview

ROOT = Path(__file__).resolve().parents[1]


def import_recordings(root=ROOT):
    if root.resolve() != build_noggenfogger.ROOT.resolve():
        raise ValueError('Pitch renderer must use the same checkout root')
    inputs = {key: root / 'spoken/herbalism' / (key + '.wav') for key in HERBS}
    missing = [str(path.relative_to(root)) for path in inputs.values() if not path.is_file()]
    if missing:
        raise ValueError('Missing recordings: ' + ', '.join(missing))
    sounds, sources, variants = [], [], []
    for key, source in inputs.items():
        digest = hashlib.sha256(source.read_bytes()).hexdigest()
        destination = root / 'Sounds' / ('voice_herb_' + key + '.ogg')
        start, end, duration = encode(source, destination)
        item = {'file': destination.relative_to(root).as_posix(), 'name': HERBS[key],
                'herb': key, 'kind': 'herb', 'school': 'all', 'duration': duration,
                'source': source.relative_to(root).as_posix(), 'source_start': start,
                'source_end': end, 'sample_rate': 44100, 'channels': 2}
        variants.append(build_noggenfogger.render(item))
        if hashlib.sha256(source.read_bytes()).hexdigest() != digest:
            raise ValueError('Original WAV changed: ' + str(source))
        sounds.append(item)
        sources.append({'file': item['source'], 'sha256': digest})
    pitch_path = root / 'noggenfogger/manifest.json'
    pitch = json.loads(pitch_path.read_text())
    replaced = {item['file'] for item in sounds}
    pitch['sounds'] = [item for item in pitch['sounds'] if item['source_file'] not in replaced] + variants
    pitch_path.write_text(json.dumps(pitch, ensure_ascii=False, indent=2) + '\n')
    (root / 'spoken/herbalism/manifest.json').write_text(json.dumps(
        {'sources': sources, 'sounds': sounds}, ensure_ascii=False, indent=2) + '\n')
    lines = ['-- Generated by tools/import_herbalism.py; original WAVs stay local.',
             'local _, addon = ...', 'addon.herbSounds = {}']
    for item in sounds:
        name = json.dumps(Path(item['file']).name)
        lines.append('addon.herbSounds.' + item['herb'] + ' = ' + name)
        lines.append('addon.soundDurations[' + name + '] = ' + str(item['duration']))
    (root / 'HerbSoundData.lua').write_text('\n'.join(lines) + '\n')
    write_preview(sounds, root)
    return sounds


def main():
    try:
        sounds = import_recordings()
    except ValueError as error:
        raise SystemExit(str(error)) from error
    print(f'Imported {len(sounds)} herb alerts plus Noggenfogger variants; original WAVs unchanged.')


if __name__ == '__main__':
    main()
