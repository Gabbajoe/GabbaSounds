#!/usr/bin/env python3
"""Encode personal mage/priest buff warnings without touching WAV originals."""
import argparse
import hashlib
import html
import json
from pathlib import Path

import build_noggenfogger
from preview_herbalism import encode

ROOT = Path(__file__).resolve().parents[1]
KINDS = {'intellect': 'Intelligenz / Brillanz', 'armor': 'Magier-Rüstungsbuff'}
PRIEST_KINDS = {'fortitude': 'Seelenstärke / Ausdauer', 'spirit': 'Göttlicher Willen',
                'innerfire': 'Inneres Feuer', 'fearward': 'Furchtzauberschutz'}
BUFF_KEYS = {'innerfire': 'innerFire', 'fearward': 'fearWard'}
PHASES = {'expiring': 'läuft in 2 Minuten ab', 'missing': 'fehlt / abgelaufen'}


def all_buff_sounds(root=ROOT):
    sounds = []
    for folder in ('spoken/mage/buffs', 'spoken/priest/buffs', 'spoken/priest/buffs/generic'):
        manifest = root / folder / 'manifest.json'
        if manifest.is_file():
            sounds.extend(json.loads(manifest.read_text())['sounds'])
    return sounds


def import_recordings(root=ROOT, priest=False, generic=False, source_overrides=None):
    if root.resolve() != build_noggenfogger.ROOT.resolve():
        raise ValueError('Pitch renderer must use the same checkout root')
    priest = priest or generic
    kinds = PRIEST_KINDS if priest else KINDS
    character = 'priest' if priest else 'mage'
    folder = root / 'spoken' / character / 'buffs'
    if generic:
        folder = folder / 'generic'
    overrides = source_overrides or {}
    valid = {kind + ':' + phase for kind in kinds for phase in PHASES}
    if not set(overrides).issubset(valid):
        raise ValueError('Unknown buff source override')
    inputs = [(kind, phase, root / overrides[kind + ':' + phase] if kind + ':' + phase in overrides else folder / kind / (phase + '.wav'))
              for kind in kinds for phase in PHASES]
    for _, _, source in inputs:
        if not source.resolve().is_relative_to(folder.resolve()) or source.suffix != '.wav':
            raise ValueError('Override must reference a WAV inside the selected source folder')
    missing = [str(source.relative_to(root)) for _, _, source in inputs if not source.is_file()]
    if missing:
        raise ValueError('Missing recordings: ' + ', '.join(missing))
    sounds, sources, variants = [], [], []
    for kind, phase, source in inputs:
        digest = hashlib.sha256(source.read_bytes()).hexdigest()
        prefix = 'voice_buff_priest_generic_' if generic else 'voice_buff_'
        destination = root / 'Sounds' / f'{prefix}{kind}_{phase}.ogg'
        start, end, duration = encode(source, destination)
        item = {'file': destination.relative_to(root).as_posix(), 'name': kinds[kind] + ' – ' + PHASES[phase],
                'buff': BUFF_KEYS.get(kind, kind), 'phase': phase, 'kind': 'buffwarning', 'school': 'all',
                'duration': duration, 'recording_sha256': digest, 'source': source.relative_to(root).as_posix(),
                'source_start': start, 'source_end': end, 'sample_rate': 44100, 'channels': 2}
        if generic:
            item['voice_profile'] = 'priest-generic'
            item['name'] = 'Priester (neutral): ' + item['name']
        variants.append(build_noggenfogger.render(item))
        if hashlib.sha256(source.read_bytes()).hexdigest() != digest:
            raise ValueError('Original recording changed: ' + str(source))
        sounds.append(item)
        sources.append({'file': item['source'], 'sha256': digest})
    pitch_path = root / 'noggenfogger/manifest.json'
    pitch = json.loads(pitch_path.read_text())
    replaced = {item['file'] for item in sounds}
    pitch['sounds'] = [item for item in pitch['sounds'] if item['source_file'] not in replaced] + variants
    pitch_path.write_text(json.dumps(pitch, ensure_ascii=False, indent=2) + '\n')
    (folder / 'manifest.json').write_text(json.dumps(
        {'sources': sources, 'sounds': sounds}, ensure_ascii=False, indent=2) + '\n')
    lines = ['-- Generated by tools/import_buff_alerts.py; WAV sources stay local.',
             'local _, addon = ...',
             'addon.buffAlertSounds = { intellect = {}, armor = {}, fortitude = {}, spirit = {}, innerFire = {}, fearWard = {} }',
             'addon.priestBuffGenericSounds = { fortitude = {}, spirit = {}, innerFire = {}, fearWard = {} }']
    combined = all_buff_sounds(root)
    for item in combined:
        filename = json.dumps(Path(item['file']).name)
        bank = 'priestBuffGenericSounds' if item.get('voice_profile') == 'priest-generic' else 'buffAlertSounds'
        lines.append('addon.' + bank + '.' + item['buff'] + '.' + item['phase'] + ' = ' + filename)
        lines.append('addon.soundDurations[' + filename + '] = ' + str(item['duration']))
    (root / 'BuffAlertSoundData.lua').write_text('\n'.join(lines) + '\n')
    write_preview(combined, root)
    return sounds


def write_preview(sounds, root=ROOT):
    preview = root / 'previews/buffs'
    preview.mkdir(parents=True, exist_ok=True)
    # The character-specific priest voice is an in-game Easter egg, not a
    # selectable public sound pack. Keep its clips in the runtime registry.
    priest_keys = {BUFF_KEYS.get(key, key) for key in PRIEST_KINDS}
    sounds = [item for item in sounds if item.get('buff') not in priest_keys
              or item.get('voice_profile') == 'priest-generic']
    cards = ''.join('<article><h2>' + html.escape(item['name']) + '</h2><audio controls preload="none" src="../../'
                    + item['file'] + '"></audio></article>' for item in sounds)
    (preview / 'index.html').write_text('''<!doctype html><html lang="de"><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1"><title>GabbaSounds – Buffwarnungen</title>
<style>body{font-family:system-ui;background:#111321;color:#eeeaf8;max-width:800px;margin:auto;padding:25px}article{background:#1e2137;padding:18px;margin:18px 0;border-radius:12px}audio{width:100%}</style>
<h1>🧙 Magier- und Priester-Buffwarnungen</h1>''' + cards + '</html>', encoding='utf-8')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group()
    group.add_argument('--priest', action='store_true', help='Import Bobselinchen personal priest recordings')
    group.add_argument('--priest-generic', action='store_true', help='Import neutral recordings for other priests')
    parser.add_argument('--source-override', action='append', default=[], metavar='BUFF:PHASE=PATH',
                        help='Select an alternative local WAV without changing the original files')
    args = parser.parse_args()
    try:
        overrides = dict(item.split('=', 1) for item in args.source_override)
        sounds = import_recordings(priest=args.priest, generic=args.priest_generic, source_overrides=overrides)
    except ValueError as error:
        raise SystemExit(str(error)) from error
    print(f'Imported {len(sounds)} buff warnings plus Noggenfogger variants; original WAVs unchanged.')


if __name__ == '__main__':
    main()
