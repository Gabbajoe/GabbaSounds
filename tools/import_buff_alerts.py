#!/usr/bin/env python3
"""Encode four mage buff warning recordings without touching their WAV originals."""
import hashlib
import html
import json
from pathlib import Path

import build_noggenfogger
from preview_herbalism import encode

ROOT = Path(__file__).resolve().parents[1]
KINDS = {'intellect': 'Intelligenz / Brillanz', 'armor': 'Magier-Rüstungsbuff'}
PHASES = {'expiring': 'läuft in 2 Minuten ab', 'missing': 'fehlt / abgelaufen'}


def import_recordings(root=ROOT):
    if root.resolve() != build_noggenfogger.ROOT.resolve():
        raise ValueError('Pitch renderer must use the same checkout root')
    inputs = [(kind, phase, root / 'spoken/mage/buffs' / kind / (phase + '.wav'))
              for kind in KINDS for phase in PHASES]
    missing = [str(source.relative_to(root)) for _, _, source in inputs if not source.is_file()]
    if missing:
        raise ValueError('Missing recordings: ' + ', '.join(missing))
    sounds, sources, variants = [], [], []
    for kind, phase, source in inputs:
        digest = hashlib.sha256(source.read_bytes()).hexdigest()
        destination = root / 'Sounds' / f'voice_buff_{kind}_{phase}.ogg'
        start, end, duration = encode(source, destination)
        item = {'file': destination.relative_to(root).as_posix(), 'name': KINDS[kind] + ' – ' + PHASES[phase],
                'buff': kind, 'phase': phase, 'kind': 'buffwarning', 'school': 'all',
                'duration': duration, 'source': source.relative_to(root).as_posix(),
                'source_start': start, 'source_end': end, 'sample_rate': 44100, 'channels': 2}
        variants.append(build_noggenfogger.render(item))
        if hashlib.sha256(source.read_bytes()).hexdigest() != digest:
            raise ValueError('Original recording changed: ' + str(source))
        sounds.append(item)
        sources.append({'file': item['source'], 'sha256': digest})
    pitch_path = root / 'noggenfogger/manifest.json'
    pitch = json.loads(pitch_path.read_text())
    replaced = {item['file'] for item in sounds}
    pitch['sounds'] = [item for item in pitch['sounds'] if item['source_file'] not in replaced] + variants
    pitch_path.write_text(json.dumps(pitch, ensure_ascii=False, indent=2) + '\n')
    (root / 'spoken/mage/buffs/manifest.json').write_text(json.dumps(
        {'sources': sources, 'sounds': sounds}, ensure_ascii=False, indent=2) + '\n')
    lines = ['-- Generated by tools/import_buff_alerts.py; WAV sources stay local.',
             'local _, addon = ...', 'addon.buffAlertSounds = { intellect = {}, armor = {} }']
    for item in sounds:
        filename = json.dumps(Path(item['file']).name)
        lines.append('addon.buffAlertSounds.' + item['buff'] + '.' + item['phase'] + ' = ' + filename)
        lines.append('addon.soundDurations[' + filename + '] = ' + str(item['duration']))
    (root / 'BuffAlertSoundData.lua').write_text('\n'.join(lines) + '\n')
    preview = root / 'previews/buffs'
    preview.mkdir(parents=True, exist_ok=True)
    cards = ''.join('<article><h2>' + html.escape(item['name']) + '</h2><audio controls preload="none" src="../../'
                    + item['file'] + '"></audio></article>' for item in sounds)
    (preview / 'index.html').write_text('''<!doctype html><html lang="de"><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1"><title>GabbaSounds – Buffwarnungen</title>
<style>body{font-family:system-ui;background:#111321;color:#eeeaf8;max-width:800px;margin:auto;padding:25px}article{background:#1e2137;padding:18px;margin:18px 0;border-radius:12px}audio{width:100%}</style>
<h1>🧙 Minibobsels Buffwarnungen</h1>''' + cards + '</html>', encoding='utf-8')
    return sounds


def main():
    try:
        sounds = import_recordings()
    except ValueError as error:
        raise SystemExit(str(error)) from error
    print(f'Imported {len(sounds)} buff warnings plus Noggenfogger variants; original WAVs unchanged.')


if __name__ == '__main__':
    main()
